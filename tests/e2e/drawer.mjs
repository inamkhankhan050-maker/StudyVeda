// Drawer, login/admin entry points and dark mode (mobile viewport)
import { chromium } from 'playwright';
import { serve } from './serve.mjs';
let pass = 0, fail = 0;
const ok = (n, c, x = '') => { c ? pass++ : fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  ' + x : ''}`); };
await serve('dist');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 360, height: 780 } });
await ctx.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
const p = await ctx.newPage();
const B = 'http://localhost:4173/studyveda';
try {
  await p.goto(B + '/', { waitUntil: 'networkidle' });
  ok('drawer hidden initially', !(await p.locator('.drawer-root.is-open').count()));
  await p.getByRole('button', { name: 'Open menu' }).click();
  await p.waitForSelector('.drawer-root.is-open');
  const box = await p.locator('.drawer').boundingBox(); await p.waitForTimeout(350);
  const box2 = await p.locator('.drawer').boundingBox();
  ok('drawer slides in from the right, full height', box2.x + box2.width <= 361 && box2.height >= 779, JSON.stringify(box2));
  ok('drawer has Dark Mode, Login, Admin Panel', await p.getByRole('switch', { name: /Dark Mode/ }).isVisible() && await p.locator('.drawer').getByRole('link', { name: 'Login' }).isVisible() && await p.locator('.drawer').getByRole('link', { name: 'Admin Panel' }).isVisible());
  ok('body scroll locked while open', (await p.evaluate(() => document.body.style.overflow)) === 'hidden');
  const acc = p.getByRole('button', { name: 'Computer MCQs' });
  await acc.click();
  ok('accordion expands', (await acc.getAttribute('aria-expanded')) === 'true' && await p.locator('#dr-computer-programming .dr-link').count() > 3);
  await p.locator('#dr-computer-programming').getByRole('link', { name: 'Python', exact: true }).click();
  await p.waitForURL(/\/subjects\/python$/);
  await p.waitForTimeout(350);
  ok('subject link navigates and closes drawer', !(await p.locator('.drawer-root.is-open').count()));
  await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(300);
  await p.keyboard.press('Escape'); await p.waitForTimeout(300);
  ok('Escape closes drawer', !(await p.locator('.drawer-root.is-open').count()) && (await p.evaluate(() => document.body.style.overflow)) !== 'hidden');
  await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(300);
  await p.mouse.click(10, 400); await p.waitForTimeout(300);
  ok('overlay tap closes drawer', !(await p.locator('.drawer-root.is-open').count()));
  await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(300);
  await p.getByRole('switch', { name: /Dark Mode/ }).click();
  ok('dark mode applies', (await p.evaluate(() => document.documentElement.dataset.theme)) === 'dark');
  const bg = await p.evaluate(() => getComputedStyle(document.body).backgroundColor);
  ok('dark background', bg === 'rgb(11, 16, 32)', bg);
  await p.goto(B + '/exams', { waitUntil: 'networkidle' });
  ok('dark mode persists across pages', (await p.evaluate(() => document.documentElement.dataset.theme)) === 'dark');
  ok('no horizontal overflow in dark mode', await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(300);
  await p.getByRole('switch', { name: /Dark Mode/ }).click();
  ok('light mode restores', (await p.evaluate(() => document.documentElement.dataset.theme)) === 'light');
  await p.locator('.drawer').getByRole('link', { name: 'Login' }).click();
  await p.waitForURL(/\/login$/);
  ok('Login opens the sign-in page', (await p.locator('h1').innerText()).length > 0);
  await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(300);
  await p.locator('.drawer').getByRole('link', { name: 'Admin Panel' }).click();
  await p.waitForURL(/\/admin$/);
  await p.waitForSelector('.admin-side', { timeout: 10000 }).catch(() => {});
  ok('Admin Panel opens the admin area', await p.locator('.admin-side').isVisible());
} catch (e) { fail++; console.log('FAIL  ' + e.message.split('\n')[0]); }
console.log(`\n${pass} passed, ${fail} failed`);
await b.close(); process.exit(fail ? 1 : 0);
