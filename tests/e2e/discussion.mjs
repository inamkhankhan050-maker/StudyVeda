// Demo-mode login + per-question discussion (mobile viewport)
import { chromium } from 'playwright';
import { serve } from './serve.mjs';
let pass = 0, fail = 0;
const ok = (n, c, x = '') => { c ? pass++ : fail++; console.log(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  ' + x : ''}`); };
await serve('dist');
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 360, height: 780 } });
await ctx.route(/fonts\.(googleapis|gstatic)\.com/, (r) => r.abort());
const p = await ctx.newPage();
const errors = []; p.on('pageerror', (e) => errors.push(e.message));
const B = 'http://localhost:4173/studyveda';
const TOPIC = B + '/subjects/aptitude/percentage';
try {
  await p.goto(TOPIC, { waitUntil: 'networkidle' });
  const first = p.locator('.q-study').first();
  await first.getByRole('button', { name: 'Discussion' }).click();
  ok('logged out: discussion asks to login', await first.getByText('Join the discussion', { exact: true }).isVisible() && await first.locator('.disc-join').getByRole('link', { name: 'Login' }).isVisible());
  ok('logged out: no comment box, no comments', !(await first.locator('textarea').count()) && !(await first.locator('.disc-item').count()));
  await first.locator('.disc-join').getByRole('link', { name: 'Login' }).click();
  await p.waitForURL(/\/login$/);
  await p.getByRole('button', { name: 'Create an account' }).click();
  await p.getByLabel('Your name').fill('Inam Test');
  await p.getByLabel('Email').fill('inam@example.com');
  await p.getByLabel('Password').fill('password123');
  await p.getByRole('button', { name: 'Create account' }).click();
  await p.waitForURL(/\/subjects\/aptitude\/percentage/);
  ok('sign-up in demo mode logs in and returns to the question page', true);
  await p.locator('.q-study').first().getByRole('button', { name: 'Discussion' }).click();
  const f = p.locator('.q-study').first();
  await f.locator('textarea').fill('Use 100 as the base value. Easy!');
  await f.getByRole('button', { name: 'Post comment' }).click();
  await f.locator('.disc-item').first().waitFor();
  ok('comment posts and shows with name', (await f.locator('.disc-item').first().innerText()).includes('Inam Test') && (await f.locator('.disc-item').first().innerText()).includes('Use 100 as the base'));
  ok('comment count shows', await f.getByText('1 Comment').isVisible());
  await p.reload({ waitUntil: 'networkidle' });
  await p.locator('.q-study').first().getByRole('button', { name: 'Discussion' }).click();
  ok('comment persists after reload', await p.locator('.q-study').first().locator('.disc-item').first().waitFor().then(() => true, () => false));
  const second = p.locator('.q-study').nth(1);
  await second.getByRole('button', { name: 'Discussion' }).click();
  await second.getByText(/No comments yet/).waitFor();
  ok('threads are per question', !(await second.locator('.disc-item').count()));
  await p.getByRole('button', { name: 'Open menu' }).click(); await p.waitForTimeout(300);
  ok('menu shows My Account + Logout when logged in', await p.locator('.drawer').getByText('My Account').isVisible() && await p.locator('.drawer').getByRole('button', { name: 'Logout' }).isVisible());
  await p.locator('.drawer').getByRole('button', { name: 'Logout' }).click(); await p.waitForTimeout(300);
  await p.locator('.q-study').first().getByRole('button', { name: 'Discussion' }).click().catch(() => {});
  const f2 = p.locator('.q-study').first();
  if (!(await f2.locator('.disc').count())) await f2.getByRole('button', { name: 'Discussion' }).click();
  ok('after logout the discussion is locked again', await f2.getByText('Join the discussion', { exact: true }).isVisible() && !(await f2.locator('.disc-item').count()));
  await p.goto(B + '/login', { waitUntil: 'networkidle' });
  await p.getByLabel('Email').fill('inam@example.com'); await p.getByLabel('Password').fill('wrongpass');
  await p.getByRole('button', { name: 'Sign in' }).click();
  ok('wrong password is rejected', await p.getByRole('alert').filter({ hasText: 'Wrong email or password' }).isVisible());
  await p.getByLabel('Password').fill('password123'); await p.getByRole('button', { name: 'Sign in' }).click();
  await p.waitForURL(/\/progress$/);
  ok('sign in with correct password works', true);
  await p.goto(TOPIC, { waitUntil: 'networkidle' });
  const f3 = p.locator('.q-study').first();
  await f3.getByRole('button', { name: 'Discussion' }).click();
  await f3.locator('.disc-item').first().waitFor();
  await f3.getByRole('button', { name: 'Delete my comment' }).click();
  await f3.getByText(/No comments yet/).waitFor();
  ok('own comment can be deleted', true);
  // tappable options
  await p.goto(TOPIC, { waitUntil: 'networkidle' });
  const q1 = p.locator('.q-study').first();
  await q1.getByRole('button', { name: /^Option A:/ }).click();
  ok('tapping a wrong option marks it red and shows the right one green', await q1.locator('.opt-tap.wrong').count() === 1 && await q1.locator('.opt-tap.correct').count() === 1 && await q1.getByText(/Wrong. The correct answer is B/).isVisible());
  ok('explanation appears after answering', await q1.locator('.explain').isVisible());
  ok('options lock after one tap', await q1.getByRole('button', { name: /^Option C:/ }).isDisabled());
  await q1.getByRole('button', { name: 'Try again' }).click();
  await q1.getByRole('button', { name: /^Option B:/ }).click();
  ok('tapping the right option says Correct', await q1.getByText('Correct! Well done.').isVisible() && !(await q1.locator('.opt-tap.wrong').count()));
  // logo
  await p.evaluate(() => window.scrollTo(0, 900)); await p.waitForTimeout(200);
  await p.locator('header .logo').click(); await p.waitForTimeout(600);
  ok('logo goes to the home page', /\/studyveda\/?$/.test(p.url()) && (await p.locator('main h1').first().innerText()).length > 0, p.url());
  await p.evaluate(() => window.scrollTo(0, 1500)); await p.waitForTimeout(200);
  await p.locator('header .logo').click(); await p.waitForTimeout(900);
  ok('logo on the home page scrolls back to top', (await p.evaluate(() => window.scrollY)) < 5);
  const w = await p.evaluate(() => document.documentElement.scrollWidth);
  ok('no horizontal overflow at 360px', w <= 360, String(w));
  ok('no page errors', errors.length === 0, errors.join(' | '));
} catch (e) { ok('unexpected error: ' + e.message, false); }
await b.close();
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
