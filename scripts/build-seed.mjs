// Generates supabase/seed.sql and src/data/seed.json from scripts/seed-data.mjs
import { createHash } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as D from './seed-data.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const uuid = (key) => {
  const h = createHash('sha1').update('studyveda:' + key).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const NOW = '2026-10-26T00:00:00.000Z';
const stamp = (i = 0) => new Date(Date.parse(NOW) + i * 60000).toISOString();

const categories = D.categories.map((c, i) => ({ id: uuid('cat:' + c.slug), ...c, sort_order: i, created_at: NOW }));
const catId = Object.fromEntries(categories.map((c) => [c.slug, c.id]));

const subjects = D.subjects.map(([slug, name, icon], i) => ({
  id: uuid('subject:' + slug), slug, name, icon, status: 'published', sort_order: i,
  description: D.subjectBlurbs[slug] || `Practise ${name} multiple-choice questions with answers and clear explanations.`,
  created_at: NOW, updated_at: NOW, created_by: null, updated_by: null,
}));
const subjId = Object.fromEntries(subjects.map((s) => [s.slug, s.id]));
const subject_categories = D.subjects.flatMap(([slug, , , cats]) => cats.map((c) => ({ subject_id: subjId[slug], category_id: catId[c] })));

const exams = D.exams.map(([slug, name, group], i) => ({
  id: uuid('exam:' + slug), slug, name, group_name: group, status: 'published', sort_order: i,
  description: D.examBlurbs[slug] || `Practice questions in the style of ${name} papers.`,
  created_at: NOW, updated_at: NOW, created_by: null, updated_by: null,
}));
const examId = Object.fromEntries(exams.map((e) => [e.slug, e.id]));

const topics = Object.entries(D.topics).flatMap(([s, list]) => list.map(([slug, name], i) => ({
  id: uuid(`topic:${s}:${slug}`), subject_id: subjId[s], slug, name, status: 'published', sort_order: i,
  description: `${name} questions for ${subjects.find((x) => x.slug === s).name}.`,
  created_at: NOW, updated_at: NOW, created_by: null, updated_by: null,
})));
const topicId = (s, t) => { const id = uuid(`topic:${s}:${t}`); if (!topics.find((x) => x.id === id)) throw new Error(`Unknown topic ${s}/${t}`); return id; };

const questions = D.questions.map((q, i) => {
  const [s, t, e, difficulty, question, a, b, c, d, correct, explanation, status = 'published'] = q;
  if (!subjId[s]) throw new Error('Unknown subject ' + s);
  if (e && !examId[e]) throw new Error('Unknown exam ' + e);
  if (!'ABCD'.includes(correct)) throw new Error('Bad answer ' + i);
  return {
    id: uuid('q:' + s + ':' + question), subject_id: subjId[s], topic_id: t ? topicId(s, t) : null, exam_id: e ? examId[e] : null,
    question, option_a: a, option_b: b, option_c: c, option_d: d, correct_option: correct, explanation,
    image_url: null, tags: [s, t].filter(Boolean), source: 'StudyVeda original', difficulty, status,
    created_at: stamp(i), updated_at: stamp(i), created_by: null, updated_by: null,
  };
});

const practice_sets = []; const practice_set_questions = [];
D.practiceSets.forEach(([slug, title, description, s, e, limit, sel], i) => {
  const id = uuid('set:' + slug);
  practice_sets.push({ id, slug, title, description, subject_id: s ? subjId[s] : null, exam_id: e ? examId[e] : null,
    time_limit_minutes: limit, status: 'published', created_at: stamp(i), updated_at: stamp(i), created_by: null, updated_by: null });
  D.questions.forEach((q, qi) => { if ((q[11] || 'published') === 'published' && sel(q)) practice_set_questions.push({ set_id: id, question_id: questions[qi].id, position: practice_set_questions.filter((x) => x.set_id === id).length }); });
});

const data = { categories, subjects, subject_categories, exams, topics, questions, practice_sets, practice_set_questions };
mkdirSync(resolve(root, 'src/data'), { recursive: true });
writeFileSync(resolve(root, 'src/data/seed.json'), JSON.stringify(data));

// ---------- SQL ----------
const lit = (v) => v === null || v === undefined ? 'null'
  : Array.isArray(v) ? `array[${v.map(lit).join(',')}]::text[]`
  : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const insert = (table, rows, cols, conflict) => rows.length === 0 ? '' :
  `insert into public.${table} (${cols.join(', ')}) values\n` +
  rows.map((r) => '  (' + cols.map((c) => lit(r[c])).join(', ') + ')').join(',\n') + `\non conflict ${conflict} do nothing;\n\n`;

let sql = `-- StudyVeda seed data (generated by scripts/build-seed.mjs — edit seed-data.mjs, then run npm run seed)\n-- Safe to re-run: existing rows are left untouched.\n\n`;
sql += insert('categories', categories, ['id', 'slug', 'name', 'description', 'sort_order'], '(slug)');
sql += insert('subjects', subjects, ['id', 'slug', 'name', 'description', 'icon', 'status', 'sort_order'], '(slug)');
sql += insert('subject_categories', subject_categories, ['subject_id', 'category_id'], '(subject_id, category_id)');
sql += insert('exams', exams, ['id', 'slug', 'name', 'group_name', 'description', 'status', 'sort_order'], '(slug)');
sql += insert('topics', topics, ['id', 'subject_id', 'slug', 'name', 'description', 'status', 'sort_order'], '(subject_id, slug)');
sql += insert('questions', questions, ['id', 'subject_id', 'topic_id', 'exam_id', 'question', 'option_a', 'option_b', 'option_c', 'option_d', 'correct_option', 'explanation', 'tags', 'source', 'difficulty', 'status', 'created_at'], '(id)');
sql += insert('practice_sets', practice_sets, ['id', 'slug', 'title', 'description', 'subject_id', 'exam_id', 'time_limit_minutes', 'status'], '(slug)');
sql += insert('practice_set_questions', practice_set_questions, ['set_id', 'question_id', 'position'], '(set_id, question_id)');
writeFileSync(resolve(root, 'supabase/seed.sql'), sql);

console.log(`Seed: ${categories.length} categories, ${subjects.length} subjects, ${exams.length} exams, ${topics.length} topics, ${questions.length} questions, ${practice_sets.length} sets`);
